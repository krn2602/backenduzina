CREATE SCHEMA IF NOT EXISTS jobfest;
CREATE TABLE IF NOT EXISTS jobfest.cv_uploads (
  path TEXT PRIMARY KEY,
  size_bytes BIGINT NOT NULL CHECK (size_bytes BETWEEN 1 AND 5242880),
  state TEXT NOT NULL DEFAULT 'pending' CHECK (state IN ('pending', 'committed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS jobfest.inscrieri (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nume TEXT NOT NULL CHECK (char_length(nume) BETWEEN 1 AND 100),
  prenume TEXT NOT NULL CHECK (char_length(prenume) BETWEEN 1 AND 100),
  email TEXT NOT NULL CHECK (char_length(email) BETWEEN 1 AND 254),
  zile JSONB NOT NULL CHECK (jsonb_typeof(zile) = 'array'),
  facultate JSONB NOT NULL CHECK (jsonb_typeof(facultate) = 'array'),
  an SMALLINT NOT NULL CHECK (an BETWEEN 1 AND 3),
  sursa TEXT NOT NULL DEFAULT '' CHECK (char_length(sursa) <= 500),
  cv_nume TEXT NOT NULL,
  cv_tip TEXT NOT NULL DEFAULT 'application/pdf',
  cv_path TEXT NOT NULL UNIQUE REFERENCES jobfest.cv_uploads(path),
  cv_size INTEGER NOT NULL CHECK (cv_size BETWEEN 1 AND 5242880),
  data_inscrierii TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS jobfest.feedback (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT CHECK (char_length(email) <= 254),
  general SMALLINT NOT NULL CHECK (general BETWEEN 1 AND 5),
  recomandare SMALLINT CHECK (recomandare BETWEEN 1 AND 5),
  bine TEXT NOT NULL DEFAULT '' CHECK (char_length(bine) <= 1000),
  zile JSONB NOT NULL CHECK (jsonb_typeof(zile) = 'array'),
  locatie SMALLINT CHECK (locatie BETWEEN 1 AND 5),
  speakeri SMALLINT CHECK (speakeri BETWEEN 1 AND 5),
  program SMALLINT CHECK (program BETWEEN 1 AND 5),
  standuri SMALLINT CHECK (standuri BETWEEN 1 AND 5),
  promovare SMALLINT CHECK (promovare BETWEEN 1 AND 5),
  schimbat TEXT NOT NULL DEFAULT '' CHECK (char_length(schimbat) <= 1000),
  facultate JSONB NOT NULL CHECK (jsonb_typeof(facultate) = 'array'),
  data_feedback TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS cv_uploads_pending ON jobfest.cv_uploads(created_at) WHERE state = 'pending';
ALTER TABLE jobfest.inscrieri ENABLE ROW LEVEL SECURITY;
ALTER TABLE jobfest.feedback ENABLE ROW LEVEL SECURITY;
ALTER TABLE jobfest.cv_uploads ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON SCHEMA jobfest FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA jobfest FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA jobfest FROM PUBLIC;
